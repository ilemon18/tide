export function paletteFor(mode: ThemeMode, systemDark: boolean): Palette {
  if (mode === 'system') return systemDark ? darkModern : lightModern
  return palettes[mode] ?? tide
}

/** Flatten a palette into CSS variables for Tailwind semantic class names */
export function cssVars(p: Palette): Record<string, string> {
  return {
    '--c-bg': p.ui.bg,
    '--c-panel': p.ui.panel,
    '--c-panel-alt': p.ui.panelAlt,
    '--c-border': p.ui.border,
    '--c-fg': p.ui.fg,
    '--c-muted': p.ui.muted,
    '--c-accent': p.ui.accent,
    '--c-accent-fg': p.ui.accentFg,
    '--c-hover': p.ui.hover,
    '--c-active': p.ui.active,
    '--c-selection': p.ui.selection,
    '--c-success': p.ui.success,
    '--c-warning': p.ui.warning,
    '--c-danger': p.ui.danger,
    '--c-tab': p.ui.tab,
    '--c-shadow': p.ui.shadow,
    // The activity bar sits one step darker than the sidebar: dark themes crush to black, light
    // themes use only a touch of foreground gray, otherwise the sidebar turns into heavy gray.
    '--c-activity-bar':
      p.id === 'tide'
        ? p.ui.panelAlt
        : p.dark
          ? `color-mix(in srgb, ${p.ui.panel} 82%, #000000)`
          : `color-mix(in srgb, ${p.ui.panel} 94%, ${p.ui.fg})`,
  }
}

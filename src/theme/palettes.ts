export type Palette = {
  id: ThemeId
  label: string
  /** Catalog key: takes precedence over label when translated (only the eyecare theme needs it today) */
  labelKey?: MessageKey
  hint: string
  group: 'dark' | 'light' | 'eyecare'
  dark: boolean
  ui: {
    bg: string
    panel: string
    panelAlt: string
    border: string
    fg: string
    muted: string
    accent: string
    accentFg: string
    hover: string
    active: string
    selection: string
    success: string
    warning: string
    danger: string
    activityBar: string
    titleBar: string
    tabBar: string
    statusBar: string
    tab: string
    shadow: string
  }
  syntax: SyntaxColors
  terminal: TerminalColors
}

type UiSpec = {
  bg: string
  panel: string
  panelAlt: string
  border: string
  fg: string
  muted: string
  accent: string
  accentFg: string
  success: string
  warning: string
  danger: string
  selection?: string
  hover?: string
  active?: string
  activityBar?: string
  titleBar?: string
  tabBar?: string
  statusBar?: string
}

function makeTheme(
  id: ThemeId,
  label: string,
  hint: string,
  group: Palette['group'],
  ui: UiSpec,
  syntax: SyntaxColors,
  terminal: TerminalColors,
  labelKey?: MessageKey,
): Palette {
  const dark = group === 'dark'
  return {
    id,
    label,
    labelKey,
    hint,
    group,
    dark,
    ui: {
      ...ui,
      hover: ui.hover ?? ui.panelAlt,
      active: ui.active ?? ui.border,
      selection: ui.selection ?? (dark ? '#3b3b6b' : '#cfe0ff'),
      activityBar: ui.activityBar ?? ui.panel,
      titleBar: ui.titleBar ?? ui.panel,
      tabBar: ui.tabBar ?? ui.panel,
      statusBar: ui.statusBar ?? ui.panel,
      tab: ui.bg,
      shadow: dark ? 'rgba(0,0,0,0.5)' : 'rgba(15,15,30,0.12)',
    },
    syntax,
    terminal,
  }
}


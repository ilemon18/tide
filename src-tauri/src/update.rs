#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct InstallOutcome {
    /// "restart" = the helper replaces the app and relaunches it; "manual" = the file was only
    /// revealed in the file manager
    pub mode: &'static str,
    /// The downloaded installer
    pub path: String,
    /// Which `.app` it will go into (macOS); empty for "manual"
    pub installed_to: String,
    /// Where the current process runs from; set only when the update lands elsewhere
    /// (e.g. an app opened from a downloaded `.dmg` installs into `~/Applications`)
    pub previous: String,
    pub log_path: String,
}

/// What this launch can say about the previous install attempt.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UpdateReport {
    /// Version the helper was asked to install
    pub attempted: String,
    /// Version actually running now
    pub current: String,
    /// False = the swap did not take: this launch is still the old build
    pub ok: bool,
    pub installed_to: String,
    pub previous: String,
    pub log_path: String,
}

/// `update-pending.json`. Same fields as [`UpdateReport`] plus a timestamp, since the file

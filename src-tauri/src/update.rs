/// Build mode for the frontend. Debug builds use Settings → About as the only update entry:
/// startup stays quiet and the title bar never advertises a release.
#[tauri::command]
pub fn is_debug_build() -> bool {
    cfg!(debug_assertions)
}

/// Debug builds may still perform an explicit user-requested check, but never the quiet startup
/// check. Kept pure so the guard is testable without an AppHandle or network access.
fn background_update_allowed(debug_build: bool, manual: bool) -> bool {
    manual || !debug_build
}

/// Ask GitHub for the latest release and compare it with the current build.
///
/// `manual` = the user clicked "check for updates": that always goes to the network (except for a
/// double click a few seconds apart), while the quiet startup check trusts the cache for hours.
/// `force` = "check latest": skip the local cache, request a revalidation from GitHub, and do not
/// fall back to an old answer when the network fails. A successful forced answer is still cached
/// for the next launch.
///
/// Every path below is served by the release CDN or the release feed. No REST API call: its
/// 60-per-hour budget is per IP and shared by everyone behind the same NAT, and exhausting it
/// used to replace every answer with "rate limited".
#[tauri::command]
pub async fn update_check<R: Runtime>(
    app: AppHandle<R>,
    manual: bool,
    force: bool,
) -> AppResult<UpdateInfo> {
    if !background_update_allowed(cfg!(debug_assertions), manual) {
        // The frontend skips this path in debug builds too. Keep the backend guard so a stale or
        // manually invoked automatic check still cannot touch the network.
        return Err(AppError::c("update.state"));
    }

    let current = app.package_info().version.to_string();
    let cached = if force {
        None
    } else {
        read_cache(&app).map(|mut cache| {
            cache.info = calibrate_cached_info(cache.info, &current);
            cache
        })
    };

    if let Some(cache) = &cached {
        if cache_is_fresh(now_ms().saturating_sub(cache.at), manual, force) {
            return Ok(cache.info.clone());
        }
    }

    let http = client()?;
    match check_online(&http, &current, force).await {
        Ok(info) => {
            let info = write_cache(&app, info);
            Ok(info)
        }
        Err(err) => {
            // Offline, a CDN hiccup, or GitHub rate-limiting the CDN: yesterday's answer beats a
            // red error, as long as the UI can say it is older than this check. A forced check
            // explicitly asked for a fresh answer, so it never takes this path.
            if cache_fallback_allowed(force) {
                if let Some(mut cache) = cached {
                    write_log(&app, &format!("update check failed, answering from cache: {err}"));
                    cache.info.stale = true;
                    return Ok(cache.info);
                }
            }
            let prefix = if force { "forced update check failed" } else { "update check failed" };
            write_log(&app, &format!("{prefix}: {err}"));
            Err(err)
        }
    }
}

/// The quota-free lookup chain: newest manifest -> newest tag -> tag manifest -> tag only.
async fn check_online(
    http: &reqwest::Client,
    current: &str,
    force: bool,
) -> AppResult<UpdateInfo> {
    // 1. The manifest attached to the newest stable release (CDN, no quota)
    if let ManifestLookup::Found(manifest) = fetch_manifest(http, &manifest_url(), force).await? {
        return Ok(info_from_manifest(*manifest, current, current_platform()));
    }

    // 2. `releases/latest` skips prereleases, and the manifest hangs on the tagged release, so
    //    the feed names the newest tag and the manifest is read from there
    let Some((tag, page_url)) = fetch_newest_tag(http, force).await? else {
        // Nothing published yet (or the repo does not exist yet): nothing to offer
        return Ok(UpdateInfo::up_to_date(current));
    };
    if let ManifestLookup::Found(manifest) =
        fetch_manifest(http, &tag_manifest_url(&tag), force).await?
    {
        return Ok(info_from_manifest(*manifest, current, current_platform()));
    }

    // 3. A release published by hand has no manifest: the tag still says whether a newer build
    //    exists, but there is no installer to download from inside the app
    Ok(info_from_tag(&tag, &page_url, current))
}

/// Read one `latest.json`. `Missing` = this release has none (prerelease, hand-made release, or
/// a broken file) and the caller should try the next step; `Err` = transport, rate limiting or a
/// server problem, a retry would fail the same way.
async fn fetch_manifest(
    http: &reqwest::Client,
    url: &str,
    force: bool,
) -> AppResult<ManifestLookup> {
    let response = check_request(http, url, "application/json", force)
        .send()
        .await
        .map_err(network)?;

    let status = response.status();
    if status == reqwest::StatusCode::NOT_FOUND {
        return Ok(ManifestLookup::Missing);
    }
    if status == reqwest::StatusCode::FORBIDDEN || status == reqwest::StatusCode::TOO_MANY_REQUESTS {
        return Err(AppError::c("update.rateLimited"));
    }
    if !status.is_success() {
        return Err(AppError::p(
            "update.httpStatus",
            [("status", status.to_string())],
        ));
    }
    let bytes = response.bytes().await.map_err(network)?;
    match serde_json::from_slice::<Manifest>(&bytes) {
        Ok(manifest) if !manifest.version.trim().is_empty() => {
            Ok(ManifestLookup::Found(Box::new(manifest)))
        }
        // A broken manifest must not kill updates: the feed below still names the newest tag
        _ => Ok(ManifestLookup::Missing),
    }
}

/// Newest release from `releases.atom` as `(tag, page url)`.
async fn fetch_newest_tag(
    http: &reqwest::Client,
    force: bool,
) -> AppResult<Option<(String, String)>> {
    let response = check_request(http, &release_feed_url(), "application/atom+xml", force)
        .send()
        .await
        .map_err(network)?;

    let status = response.status();
    if status == reqwest::StatusCode::NOT_FOUND {
        return Ok(None);
    }
    if status == reqwest::StatusCode::FORBIDDEN || status == reqwest::StatusCode::TOO_MANY_REQUESTS {
        return Err(AppError::c("update.rateLimited"));
    }
    if !status.is_success() {
        return Err(AppError::p(
            "update.httpStatus",
            [("status", status.to_string())],
        ));
    }
    let body = response.text().await.map_err(network)?;
    Ok(parse_feed(&body))
}

/// First entry of a `releases.atom` feed: `(tag, page url)`, both taken from its
/// `rel="alternate"` link, because the title is the release **name** ("Tide v0.0.4") and not the
/// tag.
///
/// Hand-parsed on purpose: an XML crate for one attribute would outweigh the whole check.
fn parse_feed(xml: &str) -> Option<(String, String)> {
    // Everything before the first `<entry` is feed metadata (its own link points at the list)
    let entry = xml.split("<entry").nth(1)?;
    let mut rest = entry;
    while let Some(at) = rest.find("href=\"") {
        let after = &rest[at + "href=\"".len()..];
        let end = after.find('"')?;
        let href = &after[..end];
        if let Some(tag) = href.split("/releases/tag/").nth(1) {
            let tag = tag.trim();
            if !tag.is_empty() {
                return Some((tag.to_string(), href.to_string()));
            }
        }
        rest = &after[end..];
    }
    None
}

/// Manifest -> decision. Kept pure so it is testable offline.
fn info_from_manifest(manifest: Manifest, current: &str, platform: Platform) -> UpdateInfo {
    let latest = manifest
        .version
        .trim()
        .trim_start_matches(['v', 'V'])
        .to_string();
    if latest.is_empty() {
        return UpdateInfo::up_to_date(current);
    }

    let asset = manifest_asset(&manifest, platform);
    let usable = asset
        .map(|a| a.size > 0 && !a.url.is_empty() && trusted_url(&a.url))
        .unwrap_or(false);
    // Drop the whole entry if it is not a GitHub TLS URL instead of just flagging it:
    // an untrusted URL must never reach the UI.
    let (asset_name, asset_size, download_url, checksum) = match (usable, asset) {
        (true, Some(asset)) => (
            asset.name.clone(),
            asset.size,
            asset.url.clone(),
            asset.sha256.trim().to_ascii_lowercase(),
        ),
        _ => (String::new(), 0, String::new(), String::new()),
    };

    UpdateInfo {
        available: usable && is_newer(&latest, current),
        has_release: true,
        current: current.to_string(),
        latest,
        name: manifest.tag,
        page_url: manifest.page_url,
        published_at: manifest.published_at,
        asset_name,
        asset_size,
        download_url,
        checksum,
        checked_at: 0,
        stale: false,
    }
}

/// Tag-only -> decision: the release exists but has no manifest, so there is no installer URL
/// (and no checksum) to offer. Kept pure so it is testable offline.
fn info_from_tag(tag: &str, page_url: &str, current: &str) -> UpdateInfo {
    let latest = tag.trim().trim_start_matches(['v', 'V']).to_string();
    if latest.is_empty() {
        return UpdateInfo::up_to_date(current);
    }
    UpdateInfo {
        available: is_newer(&latest, current),
        has_release: true,
        current: current.to_string(),
        latest,
        name: tag.trim().to_string(),
        page_url: page_url.to_string(),
        published_at: String::new(),
        asset_name: String::new(),
        asset_size: 0,
        download_url: String::new(),
        checksum: String::new(),
        checked_at: 0,
        stale: false,
    }
}

/// Stream the installer into the app cache directory and report progress.
#[tauri::command]
pub async fn update_download<R: Runtime>(
    app: AppHandle<R>,
    state: tauri::State<'_, UpdateState>,
    url: String,
    file_name: String,
    // SHA-256 from `latest.json`; empty / absent for old releases without a manifest
    checksum: Option<String>,
) -> AppResult<String> {
    if !trusted_url(&url) {
        return Err(AppError::c("update.untrusted"));
    }

    let dir = app
        .path()
        .app_cache_dir()
        .map_err(|err| AppError::p("update.noCacheDir", [("error", err.to_string())]))?
        .join("updates");
    tokio::fs::create_dir_all(&dir)
        .await
        .map_err(|err| AppError::p("update.cacheDir", [("error", err.to_string())]))?;
    // A package left from last time must never be installed by mistake
    if let Ok(mut entries) = tokio::fs::read_dir(&dir).await {
        while let Ok(Some(entry)) = entries.next_entry().await {
            let _ = tokio::fs::remove_file(entry.path()).await;
        }
    }

    let target = dir.join(sanitize_file_name(&file_name));
    let mut response = client()?
        .get(&url)
        .send()
        .await
        .map_err(network)?
        .error_for_status()
        .map_err(network)?;

    let total = response.content_length().unwrap_or(0);
    if total > MAX_ASSET_BYTES {
        return Err(AppError::c("update.tooLarge"));
    }

    emit_progress(&app, 0, total, false);
    let mut file = tokio::fs::File::create(&target)
        .await
        .map_err(|err| AppError::p("update.writeFailed", [("error", err.to_string())]))?;
    let mut received: u64 = 0;
    let mut last_emit = Instant::now();
    let mut last_percent = 0u8;
    let mut hasher = Sha256::new();

    loop {
        let chunk = match response.chunk().await {
            Ok(Some(chunk)) => chunk,
            Ok(None) => break,
            Err(err) => {
                let _ = tokio::fs::remove_file(&target).await;
                return Err(network(err));
            }
        };
        received += chunk.len() as u64;
        if received > MAX_ASSET_BYTES {
            let _ = tokio::fs::remove_file(&target).await;
            return Err(AppError::c("update.tooLarge"));
        }
        hasher.update(&chunk);
        if let Err(err) = tokio::io::AsyncWriteExt::write_all(&mut file, &chunk).await {
            let _ = tokio::fs::remove_file(&target).await;
            return Err(AppError::p("update.writeFailed", [("error", err.to_string())]));
        }
        let now = percent(received, total);
        if now != last_percent || last_emit.elapsed() >= Duration::from_millis(150) {
            last_emit = Instant::now();
            last_percent = now;
            emit_progress(&app, received, total, false);
        }
    }

    tokio::io::AsyncWriteExt::flush(&mut file)
        .await
        .map_err(|err| AppError::p("update.writeFailed", [("error", err.to_string())]))?;
    file.sync_all()
        .await
        .map_err(|err| AppError::p("update.writeFailed", [("error", err.to_string())]))?;

    if total > 0 && received != total {
        let _ = tokio::fs::remove_file(&target).await;
        return Err(AppError::p(
            "update.incomplete",
            [
                ("received", received.to_string()),
                ("total", total.to_string()),
            ],
        ));
    }

    // Integrity: the checksum travels with the manifest, so a tampered or truncated package is
    // rejected before the install
    if let Some(expected) = checksum.as_deref().map(str::trim).filter(|s| !s.is_empty()) {
        let actual = format!("{:x}", hasher.finalize());
        if !actual.eq_ignore_ascii_case(expected) {
            let _ = tokio::fs::remove_file(&target).await;
            return Err(AppError::p(
                "update.checksum",
                [("expected", expected.to_string()), ("actual", actual)],
            ));
        }
    }

    emit_progress(&app, received, total.max(received), true);
    *state
        .0
        .lock()
        .map_err(|_| AppError::c("update.state"))? = Some(target.clone());
    Ok(target.to_string_lossy().to_string())
}

/// Install the downloaded package. A helper replaces it and restarts the app after this process
/// exits.
#[tauri::command]
pub async fn update_install<R: Runtime>(
    app: AppHandle<R>,
    state: tauri::State<'_, UpdateState>,
    // Version from `latest.json`; the helper refuses any other version, so a mismatched or
    // leftover download can never be applied silently
    version: Option<String>,
) -> AppResult<InstallOutcome> {
    let archive = state
        .0
        .lock()
        .map_err(|_| AppError::c("update.state"))?
        .clone()
        .ok_or_else(|| AppError::c("update.notReady"))?;
    if !archive.exists() {
        return Err(AppError::c("update.fileGone"));
    }

    let current = app.package_info().version.to_string();
    let expected = version
        .map(|value| value.trim().trim_start_matches(['v', 'V']).to_string())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| current.clone());
    let log = log_path(&app).to_string_lossy().to_string();
    write_log(
        &app,
        &format!(
            "install requested: {current} -> {expected} ({})",
            archive.display()
        ),
    );

    // Multiple windows: installing ends the whole process, so broadcast "time to flush" to every
    // window, reusing the same flush path as a normal exit (app:hidden). Wait a bounded time.
    let _ = app.emit(FLUSH_EVENT, ());
    tokio::time::sleep(Duration::from_millis(FLUSH_GRACE_MS)).await;

    #[cfg(target_os = "macos")]
    {
        return macos_install(&app, &archive, &expected, &log);
    }

    #[cfg(target_os = "windows")]
    {
        return windows_install(&app, &archive, &expected, &log);
    }

    #[allow(unreachable_code)]
    {
        reveal(&app, &archive)?;
        Ok(InstallOutcome {
            mode: "manual",
            path: archive.to_string_lossy().to_string(),
            installed_to: String::new(),
            previous: String::new(),
            log_path: log,
        })
    }
}

/// Read (and clear) the marker `update_install` left, so the launch after "restart to install"
/// can tell the user whether the update actually took effect.
///
/// `None` = no install attempt; `Some(report)` with `ok: false` = the helper ran, but this launch
/// is still the old build (the "restarted and nothing changed" silent failure).
#[tauri::command]
pub async fn update_startup_report<R: Runtime>(app: AppHandle<R>) -> AppResult<Option<UpdateReport>> {
    let Some(file) = pending_file(&app) else {
        return Ok(None);
    };
    let Ok(bytes) = std::fs::read(&file) else {
        return Ok(None);
    };
    // Read once: reporting twice nags about an install that is already over
    let _ = std::fs::remove_file(&file);
    let Ok(pending) = serde_json::from_slice::<PendingUpdate>(&bytes) else {
        return Ok(None);
    };

    let current = app.package_info().version.to_string();
    let ok = versions_equal(&pending.attempted, &current);
    write_log(
        &app,
        &format!(
            "launch after install: wanted {} running {current} -> {}",
            pending.attempted,
            if ok { "ok" } else { "did not take effect" }
        ),
    );

    Ok(Some(UpdateReport {
        attempted: pending.attempted,
        current,
        ok,
        installed_to: pending.installed_to,
        previous: pending.previous,
        log_path: pending.log_path,
    }))
}

/// Open the release page in the browser. The next step when a release has no manifest: there is
/// no installer URL to download from inside the app, so the page is the only way forward.
#[tauri::command]
pub fn update_open_page(url: String) -> AppResult<()> {
    // Same allowlist as the download: https on GitHub hosts, so a manifest cannot send the browser
    // to somewhere else
    if !trusted_url(&url) {
        return Err(AppError::c("update.untrusted"));
    }
    let status = open_in_browser(&url)
        .map_err(|err| AppError::p("update.openFailed", [("error", err.to_string())]))?;
    // macOS `open` returns at once; elsewhere a non-zero exit means the browser never started
    if !cfg!(target_os = "macos") && !status.success() {
        return Err(AppError::c("update.openFailedStatus"));
    }
    Ok(())
}

#[cfg(target_os = "macos")]
fn open_in_browser(url: &str) -> std::io::Result<std::process::ExitStatus> {
    crate::proc::command("open").arg(url).status()
}

#[cfg(windows)]
fn open_in_browser(url: &str) -> std::io::Result<std::process::ExitStatus> {
    // `start` is a cmd builtin; the empty string is the window title it would otherwise eat
    crate::proc::command("cmd")
        .args(["/C", "start", ""])
        .arg(url)
        .status()
}

#[cfg(all(unix, not(target_os = "macos")))]
fn open_in_browser(url: &str) -> std::io::Result<std::process::ExitStatus> {
    crate::proc::command("xdg-open").arg(url).status()
}

/// Reveal a file in Finder / Explorer. Reuses `proc::command` instead of adding a plugin for this
/// one thing (on Windows it also hides the console window).
fn reveal<R: Runtime>(app: &AppHandle<R>, path: &Path) -> AppResult<()> {
    let _ = app;
    #[cfg(target_os = "macos")]
    let status = crate::proc::command("open").arg("-R").arg(path).status();
    #[cfg(windows)]
    let status = crate::proc::command("explorer")
        .arg(format!("/select,{}", path.display()))
        .status();
    #[cfg(all(unix, not(target_os = "macos")))]
    let status = crate::proc::command("xdg-open")
        .arg(path.parent().unwrap_or(path))
        .status();

    status
        .map_err(|err| AppError::p("update.revealFailed", [("error", err.to_string())]))?;
    Ok(())
}

// -------------------------------------------------------------------- macOS

/// Which `.app` this binary was launched from, if any.
#[cfg(target_os = "macos")]
fn bundle_root() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    exe.ancestors()
        .find(|path| path.extension().map(|ext| ext == "app").unwrap_or(false))
        .map(Path::to_path_buf)
}

/// A dev build under `src-tauri/target`: it must never be replaced by a release package, or
/// `tauri dev` loses the build it is running.
#[cfg(target_os = "macos")]
fn is_dev_build(bundle: &Path) -> bool {
    bundle.to_string_lossy().contains("/src-tauri/target/")
}

/// Gatekeeper runs apps opened from a quarantined location (a downloaded `.dmg`, `~/Downloads`)
/// from a random read-only mount under `/private/var/folders/.../AppTranslocation/`.
/// That path can never be replaced, and it is not where the user wants the app either.
#[cfg(target_os = "macos")]
fn is_translocated(bundle: &Path) -> bool {
    bundle.to_string_lossy().contains("/AppTranslocation/")
}

/// Whether `dir` can take new files.
///
/// The only honest test: permission bits say nothing about read-only volumes or sandboxes, so
/// create a probe file — the way Sparkle decides the same thing.
#[cfg(target_os = "macos")]
fn dir_is_writable(dir: &Path) -> bool {
    let probe = dir.join(format!(".tide-update-write-test-{}", std::process::id()));
    match std::fs::File::create(&probe) {
        Ok(mut file) => {
            let _ = file.write_all(b"ok");
            drop(file);
            let _ = std::fs::remove_file(&probe);
            true
        }
        Err(_) => false,
    }
}

/// Pick the `.app` the update should land in, in priority order:
///
/// 1. the bundle the current build runs from, if its directory is writable — the normal case,
///    and the only one without a copy;
/// 2. `/Applications/<name>` if `/Applications` is writable: the app was opened from a `.dmg`
///    or `~/Downloads`, and the user wants it where Spotlight and Launchpad find it;
/// 3. `~/Applications/<name>`, no admin password needed.
///
/// `None` means nothing is writable — the only case where the file still goes to the user.
#[cfg(target_os = "macos")]
fn choose_install_target(
    current: &Path,
    replace_in_place: bool,
    applications: &Path,
    user_applications: &Path,
    writable: impl Fn(&Path) -> bool,
) -> Option<PathBuf> {
    if replace_in_place {
        return Some(current.to_path_buf());
    }
    let name = current
        .file_name()
        .map(|name| name.to_os_string())
        .unwrap_or_else(|| "Tide.app".into());
    for dir in [applications, user_applications] {
        if !writable(dir) {
            continue;
        }
        let candidate = dir.join(&name);
        // The running bundle never becomes a candidate: excluded above
        if candidate == current {
            continue;
        }
        return Some(candidate);
    }
    None
}

#[cfg(target_os = "macos")]
fn sh_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

/// The helper that does the swap. It runs after the app exits, so it must survive on its own:
/// every step is logged, any failure reopens the currently installed app, and the extracted
/// bundle must pass the version check before anything is replaced.
#[cfg(target_os = "macos")]
const INSTALL_SCRIPT: &str = r#"#!/bin/sh
# 由 Tide 写出；跑完自删。日志：@@LOG@@
set -u
LOG=@@LOG@@
BUNDLE=@@BUNDLE@@
SOURCE=@@SOURCE@@
DMG=@@DMG@@
EXPECTED=@@EXPECTED@@
APP_PID=@@PID@@
MNT=""
STAGED="$BUNDLE.tide-new"
BACKUP="$BUNDLE.tide-old"

say() { printf '%s %s\n' "$(date '+%Y-%m-%dT%H:%M:%S')" "$*" >> "$LOG"; }

open_app() {
  if [ -d "$BUNDLE" ] && open "$BUNDLE" >> "$LOG" 2>&1; then return 0; fi
  if [ -d "$SOURCE" ] && open "$SOURCE" >> "$LOG" 2>&1; then return 0; fi
  say "could not reopen the app; it has to be started by hand"
  return 1
}

detach() {
  if [ -n "$MNT" ]; then
    hdiutil detach -force -quiet "$MNT" >> "$LOG" 2>&1 || true
    rmdir "$MNT" >/dev/null 2>&1 || true
    MNT=""
  fi
}

fail() {
  say "FAILED: $*"
  [ -d "$STAGED" ] && rm -rf "$STAGED"
  detach
  open_app
  exit 1
}

say "--- installing $EXPECTED into $BUNDLE (running from $SOURCE)"

waited=0
while kill -0 "$APP_PID" 2>/dev/null; do
  waited=$((waited + 1))
  if [ "$waited" -gt 900 ]; then fail "the app was still running after three minutes"; fi
  sleep 0.2
done
say "the app has quit"

MNT=$(mktemp -d /tmp/tide-update.XXXXXX) || fail "no mount point could be created"
mounted=0
for attempt in 1 2 3; do
  if hdiutil attach -nobrowse -noverify -quiet -mountpoint "$MNT" "$DMG" >> "$LOG" 2>&1; then
    mounted=1
    break
  fi
  say "mounting the downloaded dmg failed (attempt $attempt)"
  sleep 1
done
[ "$mounted" = 1 ] || fail "the downloaded dmg could not be mounted"

SRC=$(find "$MNT" -maxdepth 1 -name '*.app' -print 2>/dev/null | head -n 1)
[ -n "${SRC:-}" ] || fail "the dmg contains no .app"

say "unpacking $SRC"
rm -rf "$STAGED"
ditto "$SRC" "$STAGED" >> "$LOG" 2>&1 || fail "the new bundle could not be copied out of the dmg"
detach

VERSION=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' \
  "$STAGED/Contents/Info.plist" 2>/dev/null)
if [ "${VERSION:-}" != "$EXPECTED" ]; then
  fail "the dmg holds version '${VERSION:-unknown}', expected '$EXPECTED'"
fi
[ -d "$STAGED/Contents/MacOS" ] || fail "the new bundle has no Contents/MacOS"
# 下载来自 release CDN，不是 Safari：没有隔离属性要清
xattr -dr com.apple.quarantine "$STAGED" >> "$LOG" 2>&1 || true

# 通过兄弟目录换位：直接覆盖运行中的应用会留下旧版本的文件，
# 而先删掉它又会在复制失败时让用户什么都没有。
rm -rf "$BACKUP"
if [ -d "$BUNDLE" ]; then
  mv "$BUNDLE" "$BACKUP" >> "$LOG" 2>&1 || fail "the current app could not be moved aside"
fi
if ! mv "$STAGED" "$BUNDLE" >> "$LOG" 2>&1; then
  [ -d "$BACKUP" ] && mv "$BACKUP" "$BUNDLE" >> "$LOG" 2>&1
  fail "the new app could not be moved into place"
fi
rm -rf "$BACKUP"
rm -f "$DMG" >> "$LOG" 2>&1 || true
say "installed $EXPECTED into $BUNDLE"

# 应用启动时用的那份副本（挂载的 dmg、~/Downloads）现在过期了。
# 把它移进废纸篓，Mac 上只留一个 Tide，而且这个操作可撤销。
if [ "$SOURCE" != "$BUNDLE" ] && [ -d "$SOURCE" ]; then
  trash="$HOME/.Trash"
  if mkdir -p "$trash" 2>/dev/null \
    && mv "$SOURCE" "$trash/$(basename "$SOURCE")-$(date +%s)" >> "$LOG" 2>&1; then
    say "moved the old copy to the Trash: $SOURCE"
  else
    say "left the old copy in place: $SOURCE"
  fi
fi

open_app
rm -f "$0" 2>/dev/null || true
exit 0
"#;

#[cfg(target_os = "macos")]
fn macos_install<R: Runtime>(
    app: &AppHandle<R>,
    archive: &Path,
    expected: &str,
    log: &str,
) -> AppResult<InstallOutcome> {
    let bundle = bundle_root()
        .ok_or_else(|| AppError::c("update.notBundled"))?;

    let manual = |app: &AppHandle<R>| -> AppResult<InstallOutcome> {
        reveal(app, archive)?;
        Ok(InstallOutcome {
            mode: "manual",
            path: archive.to_string_lossy().to_string(),
            installed_to: String::new(),
            previous: String::new(),
            log_path: log.to_string(),
        })
    };

    // A dev build is not what the user actually runs: hand the file over
    if is_dev_build(&bundle) {
        write_log(app, "refusing to replace a developer build in src-tauri/target");
        return manual(app);
    }

    // Translocation is exactly why "the update did nothing" happened before:
    // the app runs from a read-only mount, so in-place replacement cannot work.
    let in_place = !is_translocated(&bundle)
        && bundle.parent().map(dir_is_writable).unwrap_or(false);
    let applications = PathBuf::from("/Applications");
    let user_applications = app
        .path()
        .home_dir()
        .map(|home| home.join("Applications"))
        .unwrap_or_else(|_| PathBuf::from("Applications"));
    // Create it first so the writable probe below is meaningful
    let _ = std::fs::create_dir_all(&user_applications);

    let Some(target) = choose_install_target(
        &bundle,
        in_place,
        &applications,
        &user_applications,
        dir_is_writable,
    ) else {
        write_log(app, "no writable location; the user installs by hand");
        return manual(app);
    };

    let previous = if target == bundle {
        String::new()
    } else {
        write_log(
            app,
            &format!(
                "the app runs from {} (read-only or translocated); installing into {}",
                bundle.display(),
                target.display()
            ),
        );
        bundle.to_string_lossy().to_string()
    };

    write_pending(
        app,
        &PendingUpdate {
            attempted: expected.to_string(),
            installed_to: target.to_string_lossy().to_string(),
            previous: previous.clone(),
            log_path: log.to_string(),
            at: now_ms(),
        },
    );

    let script = fill(
        INSTALL_SCRIPT,
        &[
            ("@@LOG@@", sh_quote(log)),
            ("@@BUNDLE@@", sh_quote(&target.to_string_lossy())),
            ("@@SOURCE@@", sh_quote(&bundle.to_string_lossy())),
            ("@@DMG@@", sh_quote(&archive.to_string_lossy())),
            ("@@EXPECTED@@", sh_quote(expected)),
            ("@@PID@@", std::process::id().to_string()),
        ],
    );

    let script_path = std::env::temp_dir().join(format!("tide-update-{}.sh", std::process::id()));
    if let Err(err) = std::fs::write(&script_path, script) {
        clear_pending(app);
        return Err(AppError::p(
            "update.scriptWrite",
            [("error", err.to_string())],
        ));
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&script_path, std::fs::Permissions::from_mode(0o700));
    }
    write_log(app, &format!("helper script: {}", script_path.display()));

    // Run `/bin/sh script` instead of the file itself: it lives in a temp dir, and some
    // environments mount temp as noexec.
    let mut cmd = crate::proc::command("/bin/sh");
    cmd.arg(&script_path)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null());
    if let Err(err) = cmd.spawn() {
        let _ = std::fs::remove_file(&script_path);
        clear_pending(app);
        return Err(AppError::p(
            "update.installFailed",
            [("error", err.to_string())],
        ));
    }

    exit_for_install(app);

    Ok(InstallOutcome {
        mode: "restart",
        path: archive.to_string_lossy().to_string(),
        installed_to: target.to_string_lossy().to_string(),
        previous,
        log_path: log.to_string(),
    })
}

/// Exit so the helper can replace the running file; but not before the invoke reply reaches the
/// webview.
fn exit_for_install<R: Runtime>(app: &AppHandle<R>) {
    let handle = app.clone();
    tauri::async_runtime::spawn(async move {
        tokio::time::sleep(Duration::from_millis(INSTALL_EXIT_MS)).await;
        handle.exit(0);
    });
}


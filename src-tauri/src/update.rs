//! In-app updates, sourced from GitHub Releases.
//!
//! Tide ships as a `.dmg` (macOS) or an NSIS `.exe` (Windows) at
//! `github.com/ilemon18/tide/releases`. This module implements "check -> download with
//! progress -> install" itself instead of pulling in `tauri-plugin-updater`: the official
//! updater needs a signed updater artifact, while we ship plain installers.
//!
//! The update check reads a small `latest.json` release asset
//! (`releases/latest/download/latest.json`), uploaded by the release workflow next to the
//! installers. It is served by the release CDN, so checking costs no GitHub API quota and
//! cannot hit the 60 unauthenticated requests per hour.
//!
//! The REST API is not used at all. Its budget is 60 per IP per hour, shared by everyone behind
//! the same NAT (offices, VPNs, CI), and running out of it used to turn every answer into
//! "rate limited". `releases/latest` skips prereleases, so when it has no manifest the
//! quota-free `releases.atom` feed names the newest tag and the manifest is read from that tag
//! instead. A successful answer is cached in `update-cache.json`: a startup check younger than
//! [`CACHE_FRESH_MS`] answers from disk, and a check that fails answers from the cache instead
//! of an error.
//!
//! Flow: `update_check` -> `update_download` (emits progress events) -> `update_install`
//! (spawns a one-shot helper that replaces the app once this process exits) -> on next launch
//! `update_startup_report`.
//!
//! Install is where updates fail silently most often, so every step here is made **checkable**:
//!
//! * The helper unpacks only after this process exits, **verifies the extracted version**,
//!   swaps through a sibling directory, then relaunches — any failure reopens the **old**
//!   copy.
//! * Every step is written to `update.log` (see [`log_path`]) for native diagnostics, so a
//!   failure can still be investigated without changing the install state machine.
//! * `update_install` leaves an `update-pending.json` recording the version it asked for. The
//!   next launch compares it with the running version and reports a mismatch — the only way
//!   to catch "the installer ran but did nothing" (typical on Windows).
//! * On macOS it installs into the first writable of "the running bundle / `/Applications` /
//!   `~/Applications`". An app opened straight from a downloaded `.dmg` can therefore update
//!   itself instead of answering "cannot install here".
//!
//! Safety: only `https` URLs on GitHub hosts are downloaded, the byte count and the manifest's
//! SHA-256 must match, and nothing runs before the user clicks. There is no code-signature
//! check yet — see `release/README.md`.


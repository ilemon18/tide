#[serde(rename_all = "camelCase")]
struct PendingUpdate {
    attempted: String,
    installed_to: String,
    previous: String,
    log_path: String,
    at: u64,
}

// --------------------------------------------------------------- release data

/// `latest.json`, generated by the release job. Holds only what the app needs, so the check
/// needs no REST call at all (see [`manifest_url`]).
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Manifest {
    #[serde(default)]
    version: String,
    #[serde(default)]
    tag: String,
    #[serde(default)]
    page_url: String,
    #[serde(default)]
    published_at: String,
    #[serde(default)]
    assets: ManifestAssets,
}

#[derive(Debug, Default, Deserialize)]
struct ManifestAssets {
    #[serde(default)]
    macos: Option<ManifestAsset>,
    #[serde(default)]
    windows: Option<ManifestAsset>,
}

#[derive(Debug, Deserialize)]
struct ManifestAsset {
    #[serde(default)]
    name: String,
    #[serde(default)]
    url: String,
    #[serde(default)]
    size: u64,
    #[serde(default)]
    sha256: String,
}

/// What one manifest lookup found: a usable manifest, or "this release has none"
enum ManifestLookup {
    Found(Box<Manifest>),
    Missing,
}

/// `update-cache.json`: the last successful answer and when it was fetched.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct CachedCheck {
    at: u64,
    info: UpdateInfo,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(dead_code)] // every branch is reachable, each platform just takes one
enum Platform {
    Macos,
    Windows,
    Other,
}

fn current_platform() -> Platform {
    #[cfg(target_os = "macos")]
    {
        Platform::Macos
    }
    #[cfg(target_os = "windows")]
    {
        Platform::Windows
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    {
        Platform::Other
    }
}

fn manifest_asset(manifest: &Manifest, platform: Platform) -> Option<&ManifestAsset> {
    match platform {
        Platform::Macos => manifest.assets.macos.as_ref(),
        Platform::Windows => manifest.assets.windows.as_ref(),
        Platform::Other => None,
    }
}

/// `1.2.0` > `1.1.9`, `v1.2.0` == `1.2.0`, and a release beats its own prerelease.
fn is_newer(candidate: &str, current: &str) -> bool {
    fn parse(value: &str) -> (Vec<u64>, Option<String>) {
        let trimmed = value.trim().trim_start_matches(['v', 'V']);
        let (core, pre) = match trimmed.split_once('-') {
            Some((core, pre)) => (core, Some(pre.to_ascii_lowercase())),
            None => (trimmed, None),
        };
        let numbers = core
            .split('.')
            .map(|part| {
                part.chars()
                    .take_while(|c| c.is_ascii_digit())
                    .collect::<String>()
                    .parse::<u64>()
                    .unwrap_or(0)
            })
            .collect();
        (numbers, pre)
    }

    let (a, a_pre) = parse(candidate);
    let (b, b_pre) = parse(current);
    for index in 0..a.len().max(b.len()) {
        let left = a.get(index).copied().unwrap_or(0);
        let right = b.get(index).copied().unwrap_or(0);
        if left != right {
            return left > right;
        }
    }
    match (a_pre, b_pre) {
        (None, Some(_)) => true,
        (Some(_), None) => false,
        (left, right) => left > right,
    }
}

/// Accept only TLS URLs on GitHub hosts.
fn trusted_url(raw: &str) -> bool {
    let Ok(url) = reqwest::Url::parse(raw) else {
        return false;
    };
    if url.scheme() != "https" {
        return false;
    }
    match url.host_str() {
        Some("github.com") => true,
        Some(host) => host.ends_with(".githubusercontent.com"),
        None => false,
    }
}

fn client() -> AppResult<reqwest::Client> {
    reqwest::Client::builder()
        .user_agent(USER_AGENT)
        .timeout(Duration::from_secs(120))
        .build()
        .map_err(|err| AppError::p("update.network", [("error", err.to_string())]))
}

/// Build a version lookup request. Forced checks ask every HTTP cache on the way for a
/// revalidation instead of a stored response.
fn check_request(
    http: &reqwest::Client,
    url: &str,
    accept: &str,
    force: bool,
) -> reqwest::RequestBuilder {
    let request = http.get(url).header("Accept", accept);
    if force {
        request.header("Cache-Control", "no-cache")
    } else {
        request
    }
}

fn network(err: impl std::fmt::Display) -> AppError {
    AppError::p("update.network", [("error", err.to_string())])
}

fn percent(received: u64, total: u64) -> u8 {
    if total == 0 {
        return 0;
    }
    ((received.saturating_mul(100) / total).min(100)) as u8
}

fn emit_progress<R: Runtime>(app: &AppHandle<R>, received: u64, total: u64, done: bool) {
    let _ = app.emit(
        PROGRESS_EVENT,
        UpdateProgress {
            received,
            total,
            percent: percent(received, total),
            done,
        },
    );
}

fn sanitize_file_name(raw: &str) -> String {
    let name: String = raw
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_'))
        .collect();
    if name.is_empty() {
        "tide-update".to_string()
    } else {
        name
    }
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// macOS: `~/Library/Logs/com.aitify.tide/update.log`.
/// Windows: `%LOCALAPPDATA%\com.aitify.tide\logs\update.log`.
fn log_path<R: Runtime>(app: &AppHandle<R>) -> PathBuf {
    let dir = app
        .path()
        .app_log_dir()
        .unwrap_or_else(|_| std::env::temp_dir().join("tide-logs"));
    let _ = std::fs::create_dir_all(&dir);
    dir.join(LOG_FILE)
}

fn write_log<R: Runtime>(app: &AppHandle<R>, message: &str) {
    let file = log_path(app);
    if let Ok(meta) = std::fs::metadata(&file) {
        if meta.len() > LOG_MAX_BYTES {
            let _ = std::fs::remove_file(&file);
        }
    }
    if let Ok(mut handle) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&file)
    {
        let _ = writeln!(handle, "[{}] {}", now_ms(), message.trim());
    }
}

fn pending_file<R: Runtime>(app: &AppHandle<R>) -> Option<PathBuf> {
    app.path()
        .app_config_dir()
        .ok()
        .map(|dir| dir.join(PENDING_FILE))
}

fn cache_file<R: Runtime>(app: &AppHandle<R>) -> Option<PathBuf> {
    app.path().app_config_dir().ok().map(|dir| dir.join(CACHE_FILE))
}

/// Should a cached answer be reused instead of asking GitHub again?
///
/// A click is deliberate, so only a click a few seconds old is reused (a double click must not
/// cost two requests); the quiet startup check is happy with hours. A forced check bypasses the
/// cache entirely. Kept pure for the tests.
fn cache_is_fresh(age_ms: u64, manual: bool, force: bool) -> bool {
    !force && age_ms < if manual { CACHE_CLICK_MS } else { CACHE_FRESH_MS }
}

/// A normal check may answer from the last successful result when the network fails. A forced
/// check must surface that failure instead of pretending an old answer is the latest one.
fn cache_fallback_allowed(force: bool) -> bool {
    !force
}

/// `None` = never checked, or the file is unreadable — both mean "ask GitHub"
fn read_cache<R: Runtime>(app: &AppHandle<R>) -> Option<CachedCheck> {
    let file = cache_file(app)?;
    let bytes = std::fs::read(file).ok()?;
    serde_json::from_slice::<CachedCheck>(&bytes).ok()
}

/// Stores `info` with "now" as its timestamp and hands it back stamped, so the caller and the UI
/// tell the same time.
///
/// Best effort: a failure here costs one extra request next launch, nothing else.
fn write_cache<R: Runtime>(app: &AppHandle<R>, mut info: UpdateInfo) -> UpdateInfo {
    let at = now_ms();
    info.checked_at = at;
    info.stale = false;
    let cached = CachedCheck {
        at,
        info: info.clone(),
    };
    if let Some(file) = cache_file(app) {
        if let Ok(text) = serde_json::to_vec_pretty(&cached) {
            let _ = crate::paths::write_atomic(&file, &text);
        }
    }
    info
}

/// Clear the marker so a helper that never started is not reported as a failed install on the
/// next launch.
fn clear_pending<R: Runtime>(app: &AppHandle<R>) {
    if let Some(file) = pending_file(app) {
        let _ = std::fs::remove_file(file);
    }
}

fn write_pending<R: Runtime>(app: &AppHandle<R>, pending: &PendingUpdate) {
    let Some(file) = pending_file(app) else {
        return;
    };
    if let Ok(text) = serde_json::to_vec_pretty(pending) {
        let _ = crate::paths::write_atomic(&file, &text);
    }
}

/// `v0.0.2` and `0.0.2` name the same build; anything else must match exactly.
fn versions_equal(left: &str, right: &str) -> bool {
    let normalize = |value: &str| value.trim().trim_start_matches(['v', 'V']).to_string();
    normalize(left) == normalize(right)
}

/// Re-evaluate a cached answer against the version that is actually running now.
///
/// The cache can outlive an in-app update: a check made by 0.0.1 can still be fresh after the app
/// has restarted as 0.0.2. Update `current`, and if the cached release is no longer newer, hide
/// the obsolete download entry. A genuinely newer cached release stays available.
fn calibrate_cached_info(mut info: UpdateInfo, current: &str) -> UpdateInfo {
    info.current = current.to_string();
    if !is_newer(&info.latest, current) {
        info.available = false;
    }
    info
}

/// Fill the `@@NAME@@` placeholders in a helper script.
///
/// The scripts are shell / PowerShell source full of braces, quotes and `$`, so they stay plain
/// templates replaced here rather than going through `format!` (where every `{` needs escaping).
#[cfg(any(target_os = "macos", target_os = "windows"))]
fn fill(template: &str, values: &[(&str, String)]) -> String {
    let mut out = template.to_string();
    for (key, value) in values {
        out = out.replace(key, value);
    }
    out
}

